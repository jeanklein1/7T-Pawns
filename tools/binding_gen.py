def diff_relation(name, tree_rel, schema_rel, out):
    """Symbol-keyed, both directions."""
    bad = 0
    tk, sk = set(tree_rel), set(schema_rel)
    for k in sorted(tk - sk, key=repr):
        out.append("  %s: %r in tree, absent from schema" % (name, k))
        bad += 1
    for k in sorted(sk - tk, key=repr):
        out.append("  %s: %r in schema, absent from tree" % (name, k))
        bad += 1
    for k in sorted(tk & sk, key=repr):
        t, s = tree_rel[k], schema_rel[k]
        if isinstance(t, dict) and isinstance(s, dict):
            for col in sorted(set(t) | set(s)):
                if t.get(col) != s.get(col):
                    out.append("  %s[%r].%s: tree %r, schema %r"
                               % (name, k, col, t.get(col), s.get(col)))
                    bad += 1
        elif t != s:
            out.append("  %s[%r]: tree %r, schema %r" % (name, k, t, s))
            bad += 1
    return bad


def ledger_cardinalities():
    led = BL.read(LEDGER_MD)
    m1 = re.search(r"(\d+) module-scope declarations over (\d+) `\(group, binding\)` slots", led)
    m2 = re.search(r"One row per `\(bind group layout, entry index\)`, (\d+) rows over (\d+) layouts", led)
    m3 = re.search(r"(\d+) bind groups over (\d+) layouts, every one a bijection", led)
    m4 = re.search(r"(\d+) pipelines: \d+ with exactly one call shape", led)
    if not (m1 and m2 and m3 and m4):
        stop("the ledger does not state its counts \u2014 S-1 cannot read its authority")
    return {"decls": int(m1.group(1)), "slots": int(m1.group(2)),
            "seats": int(m2.group(1)), "layouts": int(m2.group(2)),
            "groups": int(m3.group(1)), "pipelines": int(m4.group(1))}


